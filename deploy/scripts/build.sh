#!/bin/bash

# =============================================================================
# 生产环境构建脚本
#
# 功能说明：
# - 清理旧的构建文件和依赖
# - 安装生产环境依赖
# - 编译 TypeScript 代码
# - 创建运行时必要目录
#
# 使用场景：
# - 本地构建后手动部署
# - CI/CD 流水线中的构建步骤
# - 开发环境验证构建结果
#
# 使用方法：
# 1. 在项目根目录执行
# 2. 运行：./deploy/scripts/build.sh
#
# 构建流程：
# 1. 环境检查
# 2. 清理旧文件
# 3. 安装依赖
# 4. 编译代码
# 5. 创建目录
# =============================================================================

echo "🔨 开始构建生产环境..."

# -----------------------------------------------------------------------------
# 环境检查阶段
# 确保在正确的目录执行构建
# -----------------------------------------------------------------------------

# 检查是否在项目根目录
# 通过检查 package.json 文件确认目录位置
if [ ! -f "package.json" ]; then
    echo "❌ 请在项目根目录执行此脚本"
    echo "   正确路径：./deploy/scripts/build.sh"
    exit 1
fi

# -----------------------------------------------------------------------------
# 清理阶段
# 删除旧的构建产物和依赖，确保干净的构建环境
# -----------------------------------------------------------------------------

echo "🧹 清理旧文件..."

# 删除编译输出目录
# dist 目录包含之前编译的 JavaScript 文件
rm -rf dist

# 删除 node_modules 目录
# 确保使用最新的依赖版本，避免缓存问题
rm -rf node_modules

# -----------------------------------------------------------------------------
# 依赖安装阶段
# 安装项目运行所需的所有依赖包
# -----------------------------------------------------------------------------

echo "📦 安装依赖..."

# 使用 npm ci 而不是 npm install
# npm ci 的优势：
# - 更快的安装速度
# - 严格按照 package-lock.json 安装
# - 确保依赖版本一致性
# - 适合生产环境和 CI/CD
npm ci

# -----------------------------------------------------------------------------
# 代码编译阶段
# 将 TypeScript 代码编译为 JavaScript
# -----------------------------------------------------------------------------

echo "🏗️ 构建项目..."

# 执行构建命令
# 通常会执行以下操作：
# - TypeScript 编译 (tsc)
# - 代码优化和压缩
# - 静态资源处理
# - 生成 source map（如果配置）
npm run build

# -----------------------------------------------------------------------------
# 目录创建阶段
# 创建应用运行时需要的目录
# -----------------------------------------------------------------------------

echo "📁 创建目录..."

# 创建运行时必要目录：
# - uploads: 文件上传存储目录
# - logs: 应用日志存储目录
# - static: 静态资源目录
# -p 参数：如果目录已存在则不报错，如果父目录不存在则创建
mkdir -p uploads logs static

# -----------------------------------------------------------------------------
# 构建完成
# -----------------------------------------------------------------------------

echo "✅ 构建完成！"
echo ""
echo "📋 构建结果："
echo "   📁 编译输出: ./dist/"
echo "   📁 上传目录: ./uploads/"
echo "   📁 日志目录: ./logs/"
echo "   📁 静态资源: ./static/"
echo ""
echo "🚀 下一步："
echo "   - 本地运行: npm run start:prod"
echo "   - Docker 部署: cd deploy && ./scripts/deploy.sh"
echo "   - PM2 部署: pm2 start deploy/config/ecosystem.config.js --env production"
